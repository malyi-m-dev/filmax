package com.filmax.core.domain.catalog

/**
 * Раздел каталога — готовая выборка, в которую ведут чипы и шторка «Разделы» на Главной. Домен
 * называет раздел, а что он значит для выдачи (тип, фильтр, сортировка), решает модель каталога.
 *
 * Только то, что kino.pub умеет отфильтровать: «Мультфильмов», «Каналов» и «Спорта» отдельным
 * типом в API нет, а раздел, который показывает весь каталог, хуже отсутствующего.
 */
enum class CatalogSection {
    MOVIES,
    SERIES,
    ANIME,
    DOCUMENTARY,

    /** ТВ-шоу — тип `tvshow`. */
    TV_SHOWS,

    /** Концерты — тип `concert`. */
    CONCERTS,

    /** Только 4K. */
    UHD,

    /** Недавно добавленные — каталог по дате добавления. */
    FRESH,
    ;

    companion object {
        /** Раздел по имени из адреса навигации; незнакомое имя — null, а не падение экрана. */
        fun from(name: String?): CatalogSection? = entries.firstOrNull { it.name == name }
    }
}
